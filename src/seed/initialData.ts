function buildGrants(
  resource: PermissionResource,
  actions: PermissionAction[],
  scope: PermissionScope,
  moduleCode?: string,
): PermissionGrant[] {
  return actions.map((action) => ({
    resource,
    action,
    scope,
    moduleCode,
  }));
}

